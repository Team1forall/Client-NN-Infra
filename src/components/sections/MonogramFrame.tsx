type Props = {
  monogram: string;
  /** Accessible description of the placeholder. */
  label: string;
  /** "archive": stone + grain (the founder). "sage": the next generation. */
  tone: "archive" | "sage";
  /** Which half of the shared contour drawing this sheet shows. */
  sheet: "left" | "right";
  className?: string;
};

/**
 * Designed placeholder for a leadership portrait: a drawing-set sheet with
 * contour linework, a large monogram and a "Portrait to be supplied" note.
 * Never replaced by a stock or generated face.
 */
export function MonogramFrame({ monogram, label, tone, sheet, className }: Props) {
  return (
    <div
      className={[styles.mono, tone === "archive" ? "grain" : "", className].filter(Boolean).join(" ")}
      data-tone={tone}
      role="img"
      aria-label={label}
    >
      <svg
        className={styles.monoContours}
        viewBox={sheet === "left" ? "0 0 400 500" : "400 0 400 500"}
        preserveAspectRatio="xMidYMid slice"
        fill="none"
        aria-hidden="true"
        data-reveal="draw"
      >
        {CONTOURS.map((d, i) => (
          <path key={i} d={d} pathLength="1" style={{ "--i": i } as CSSProperties} />
        ))}
      </svg>
      <span className={styles.monoBorder} aria-hidden="true" />
      <span className={styles.monogram} aria-hidden="true">
        {monogram}
      </span>
      <span className={`annot ${styles.monoNote}`} aria-hidden="true">
        {PENDING}
      </span>
      <span className="cropmarks" aria-hidden="true">
        <i />
        <i />
        <i />
        <i />
      </span>
    </div>
  );
}
